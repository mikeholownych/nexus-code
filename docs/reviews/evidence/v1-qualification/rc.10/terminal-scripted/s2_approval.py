import sys, os, time; sys.path.insert(0, "."); from ptylib import *
gw, ep, log = start_gw("write", "s2")
env, ws, home = make_env("s2", ep)
s = Session(tui_argv(ws, ep, approve=True), env, 40, 14, ws, "s2")
try:
    s.wait("enter send", 15, "idle"); s.dump("idle-review-mode")
    s.type("create hello.txt\r", gap=0.03)
    # continuous typing spanning panel appearance (mock delays 1.5s)
    s.type("yes y y please yy\ry\r", gap=0.12, label="continuous typing w/ y and Enter across panel")
    s.wait("hello.txt", 5, "panel"); s.dump("panel-after-typing")
    print("file exists after typing:", os.path.exists(ws + "/hello.txt"))
    s.send(b"\x1b[200~y\ny\nyes\n\x1b[201~", label="bracketed paste y/Enter")
    s.pump(1); s.dump("after-paste"); print("file after paste:", os.path.exists(ws + "/hello.txt"))
    s.send(b"yyyyyyyy\r\r\r", label="unbracketed burst")
    s.pump(1); print("file after burst:", os.path.exists(ws + "/hello.txt"))
    s.dump("approval-40x14")
    s.send(b"y", label="y at 40x14"); s.pump(1); print("file after y@40:", os.path.exists(ws + "/hello.txt"))
    s.pump(2.5)
    s.send(b"y", label="deliberate y after 2.5s quiet"); s.pump(1); s.dump("after-deliberate-y")
    print("file after deliberate y:", os.path.exists(ws + "/hello.txt"))
    s.send(b"\x1b[D", label="Left (deliberate approve selection)"); s.pump(2.3); s.send(b"\r", label="Enter#1"); s.pump(0.6); s.dump("after-enter1")
    print("file after enter1:", os.path.exists(ws + "/hello.txt"))
    s.send(b"\r", label="Enter#2"); s.pump(3); s.dump("after-enter2")
    print("file after enter2:", os.path.exists(ws + "/hello.txt"))
finally:
    s.close(); gw.terminate()

import { HunkStager } from "../snap/cli/src/stager.ts";
import { execFileSync } from "node:child_process";
import * as fs from "node:fs"; import * as path from "node:path"; import * as os from "node:os";
const d = fs.mkdtempSync(path.join(os.tmpdir(), "a2stager-"));
const g = (...a: string[]) => execFileSync("git", a, { cwd: d, encoding: "utf-8" });
g("init", "-q"); g("config", "user.email", "a@b"); g("config", "user.name", "a");
const lines = Array.from({ length: 40 }, (_, i) => `line ${i}`);
fs.writeFileSync(path.join(d, "f.txt"), lines.join("\n") + "\n");
fs.writeFileSync(path.join(d, "my file.txt"), "a\nb\n");
g("add", "."); g("commit", "-qm", "init");
lines[2] = "CHANGED 2"; lines[35] = "CHANGED 35";
fs.writeFileSync(path.join(d, "f.txt"), lines.join("\n") + "\n");
fs.writeFileSync(path.join(d, "my file.txt"), "a\nB\n");
const s = new HunkStager(d);
const files = s.getParsedUnstagedDiff();
for (const f of files) console.log("file", JSON.stringify(f.oldPath), JSON.stringify(f.newPath), "hunks", f.hunks.length, "last line of last hunk:", JSON.stringify(f.hunks.at(-1)!.lines.at(-1)));
const f = files.find((x) => x.newPath.includes("f.txt"))!;
console.log("stage last hunk of f.txt:", JSON.stringify(s.stageHunk(f, f.hunks[1])));
console.log("cached:", g("diff", "--cached", "--stat").trim());
const sp = files.find((x) => x.oldPath.startsWith("my"))!;
console.log("stage hunk of 'my file.txt':", JSON.stringify(s.stageHunk(sp, sp.hunks[0])));
console.log("discard first hunk of f.txt:", JSON.stringify(s.discardHunk(f, f.hunks[0])));
console.log("worktree diff now:", g("diff", "--stat").trim() || "(none)");
fs.rmSync(d, { recursive: true, force: true });
